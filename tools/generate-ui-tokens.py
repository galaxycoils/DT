#!/usr/bin/env python3
"""Generate native, companion, React web, and mobile UI tokens from ui/design-tokens.json."""
import json
import shutil
import subprocess
from pathlib import Path


def to_camel(name: str) -> str:
    parts = name.split('_')
    return parts[0] + ''.join(p.capitalize() for p in parts[1:])


root = Path(__file__).resolve().parents[1]
spec = json.loads((root / 'ui/design-tokens.json').read_text())
rust = ['// Generated by tools/generate-ui-tokens.py. Edit ui/design-tokens.json.', '#![allow(dead_code)]', 'use eframe::egui::Color32;']
css = ['/* Generated from ui/design-tokens.json. Rakazo semantic palette, Apache-2.0. */']
web_css = ['/* Generated from ui/design-tokens.json. Rakazo semantic palette, Apache-2.0. */']
mobile_ts = ['// Generated by tools/generate-ui-tokens.py. Edit ui/design-tokens.json.']

for theme, colors in spec['colors'].items():
    selector = (':root,\n' if theme == 'dark' else '') + f'[data-theme="{theme}"] {{'
    css.append((':root, ' if theme == 'dark' else '') + f'[data-theme="{theme}"] {{')
    css.append(f'  color-scheme: {theme};')
    web_css.append(selector)
    web_css.append(f'  color-scheme: {theme};')
    mobile_ts.append(f'export const {theme}Tokens = {{')
    for name, value in colors.items():
        css_var = f'  --{name.replace("_", "-")}: {value};'
        css.append(css_var)
        web_css.append(css_var)
        mobile_ts.append(f'  {to_camel(name)}: "{value}",')
        channels = bytes.fromhex(value[1:])
        red, green, blue = channels[:3]
        alpha = channels[3] if len(channels) == 4 else 255
        values = [(channel * alpha + 127) // 255 for channel in (red, green, blue)] + [alpha]
        rust.append('pub const ' + theme.upper() + '_' + name.upper() + ': Color32 = Color32::from_rgba_premultiplied(' + ', '.join(map(str, values)) + ');')
    css.append('}')
    web_css.append('  --radius: 0.75rem;')
    web_css.append('}')
    mobile_ts.append('} as const;')

web_css.extend([
    '',
    'body {',
    '  margin: 0;',
    '  background: var(--background);',
    '  color: var(--foreground);',
    '  font-family: system-ui, -apple-system, sans-serif;',
    '}',
])
mobile_ts.append('export const layoutMetrics = {')
for name, value in spec['metrics'].items():
    rust.append('pub const ' + name.upper() + ': f32 = ' + str(float(value)) + ';')
    mobile_ts.append(f'  {to_camel(name)}: {value},')
mobile_ts.append('} as const;')

(root / 'crates/gm-ui/src/ui/tokens.rs').write_text('\n'.join(rust) + '\n')
formatter = shutil.which('rustfmt') or str(Path.home() / '.cargo/bin/rustfmt')
subprocess.run([formatter, str(root / 'crates/gm-ui/src/ui/tokens.rs')], check=True)
(root / 'crates/gm-openbot/src/companion_tokens.css').write_text('\n'.join(css) + '\n')
(root / 'clients/web/src/tokens.css').write_text('\n'.join(web_css) + '\n')
(root / 'clients/mobile/lib/tokens.ts').write_text('\n'.join(mobile_ts) + '\n')
print('Generated Rust, companion, React web, and mobile design tokens')
