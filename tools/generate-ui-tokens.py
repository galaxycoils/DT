#!/usr/bin/env python3
"""Generate both UI renderers' semantic tokens from the pinned design specification."""
import json
import shutil
import subprocess
from pathlib import Path

root = Path(__file__).resolve().parents[1]
spec = json.loads((root / 'ui/design-tokens.json').read_text())
rust = ['// Generated by tools/generate-ui-tokens.py. Edit ui/design-tokens.json.', '#![allow(dead_code)]', 'use eframe::egui::Color32;']
css = ['/* Generated from ui/design-tokens.json. Rakazo semantic palette, Apache-2.0. */']
for theme, colors in spec['colors'].items():
    css.append((':root, ' if theme == 'dark' else '') + '[data-theme="' + theme + '"] {')
    css.append('  color-scheme: ' + theme + ';')
    for name, value in colors.items():
        css.append('  --' + name.replace('_', '-') + ': ' + value + ';')
        channels = bytes.fromhex(value[1:])
        red, green, blue = channels[:3]
        alpha = channels[3] if len(channels) == 4 else 255
        values = [(channel * alpha + 127) // 255 for channel in (red, green, blue)] + [alpha]
        rust.append('pub const ' + theme.upper() + '_' + name.upper() + ': Color32 = Color32::from_rgba_premultiplied(' + ', '.join(map(str, values)) + ');')
    css.append('}')
for name, value in spec['metrics'].items():
    rust.append('pub const ' + name.upper() + ': f32 = ' + str(float(value)) + ';')
(root / 'crates/gm-ui/src/ui/tokens.rs').write_text('\n'.join(rust) + '\n')
formatter=shutil.which('rustfmt') or str(Path.home()/'.cargo/bin/rustfmt')
subprocess.run([formatter,str(root/'crates/gm-ui/src/ui/tokens.rs')],check=True)
(root / 'crates/gm-openbot/src/companion_tokens.css').write_text('\n'.join(css) + '\n')
print('Generated Rust and companion design tokens')
